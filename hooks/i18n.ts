export const TEXT: Record<Lang, Text> = { th, en }

/** How long ago, in the person's language. */
export function ago(ms: number, now: number, text: Text): string {
  const minutes = Math.floor((now - ms) / 60_000)
  if (minutes < 1) return text.justNow
  if (minutes < 60) return text.minutesAgo(minutes)
  const hours = Math.floor(minutes / 60)
  if (hours < 24) return text.hoursAgo(hours)
  const days = Math.floor(hours / 24)
  if (days < 7) return text.daysAgo(days)

  return text.date(new Date(ms))
}
